const DICTIONARIES: Record<Locale, Record<MessageKey, string>> = { ar, en };

export type Translator = (key: MessageKey) => string;

export function getDictionary(locale: Locale): Record<MessageKey, string> {
  return DICTIONARIES[locale];
}

export function translator(locale: Locale): Translator {
  const dict = DICTIONARIES[locale];
  return (key) => dict[key];
}

/** Picks the Arabic or English column of a bilingual database row. */
export function pick(locale: Locale, arabic: string, english: string): string {
  return locale === 'ar' ? arabic : english || arabic;
}
